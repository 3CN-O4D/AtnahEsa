-- ============================================================
-- WhatsApp autonomy, self-activity tracking and call log
-- ------------------------------------------------------------
-- 1. The bot has exactly three states: autonomous, regular, off.
--    `autonomous` never waits for approval; `regular` queues marketing
--    drafts for an admin; `off` stops AI replies.
-- 2. `whatsapp_activity` is the bot's own diary: every status/group post,
--    every outbound call and every escalation is recorded with the listing,
--    phone or target it touched. It is how the worker notices "I have
--    already posted this house five times today" and stops.
-- 3. Indexes make the "what did I do in the last 24 hours?" query cheap.
--
-- Run in Supabase SQL Editor. Safe to re-run.
-- ============================================================

-- ------------------------------------------------------- three-state mode
alter table public.whatsapp_bot_control
  drop constraint if exists whatsapp_bot_control_mode_check;

update public.whatsapp_bot_control
set mode = case
  when mode in ('autonomous', 'regular', 'off') then mode
  when mode = 'paused' then 'off'
  else 'regular'
end
where mode not in ('autonomous', 'regular', 'off');

alter table public.whatsapp_bot_control
  alter column mode set default 'regular';

alter table public.whatsapp_bot_control
  add constraint whatsapp_bot_control_mode_check
  check (mode in ('autonomous', 'regular', 'off'));

comment on column public.whatsapp_bot_control.mode is
  'autonomous = no approvals; regular = marketing needs approval; off = AI silent.';

-- Marketing cadence: about every 2.5 hours, at least 10 statuses a day.
alter table public.whatsapp_bot_control
  alter column status_interval_minutes set default 150;

alter table public.whatsapp_bot_control
  alter column status_daily_limit set default 12;

-- Only lift the old default; an admin who deliberately chose a lower cap keeps it.
update public.whatsapp_bot_control
set status_daily_limit = 12
where status_daily_limit < 10;

-- --------------------------------------------------------- activity diary
create table if not exists public.whatsapp_activity (
  id bigint generated by default as identity primary key,
  kind text not null,
  -- Listing id, phone number, group jid or admin topic, depending on `kind`.
  subject text,
  detail jsonb not null default '{}'::jsonb,
  actor text not null default 'ase',
  created_at timestamptz not null default now()
);

create index if not exists whatsapp_activity_created_idx
  on public.whatsapp_activity (created_at desc);

create index if not exists whatsapp_activity_kind_idx
  on public.whatsapp_activity (kind, created_at desc);

create index if not exists whatsapp_activity_subject_idx
  on public.whatsapp_activity (subject, created_at desc);

alter table public.whatsapp_activity enable row level security;

comment on table public.whatsapp_activity is
  'The bot''s own activity log: marketing posts, calls, escalations and admin commands.';

-- Helpful for the duplicate check: one listing should not be posted repeatedly.
create index if not exists whatsapp_marketing_sent_listing_idx
  on public.whatsapp_marketing (listing_id, channel, sent_at desc)
  where status = 'sent';
