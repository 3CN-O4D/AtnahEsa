-- WhatsApp bot console: configurable reply/group rules, status modes and history.
--
-- Service-role only. Every table is RLS-enabled with no policies; the Baileys
-- worker and the admin APIs are the only clients. This migration is additive so
-- it is safe to run on a live database.

-- ------------------------------------------------------------------- rules
-- One row. `settings` is a JSON object; unknown/missing keys fall back to the
-- defaults defined in whatsapp/lib/rules.mjs so old rows keep working.
create table if not exists public.whatsapp_bot_rules (
  id smallint primary key default 1 check (id = 1),
  settings jsonb not null default '{}'::jsonb,
  updated_by text,
  updated_at timestamptz not null default now()
);

insert into public.whatsapp_bot_rules (id)
values (1)
on conflict (id) do nothing;

alter table public.whatsapp_bot_rules enable row level security;

-- ----------------------------------------------------------------- status
-- Status mode scheduler. Kept separate from whatsapp_bot_control so the legacy
-- marketing cadence settings continue to work untouched.
create table if not exists public.whatsapp_status_settings (
  id smallint primary key default 1 check (id = 1),
  mode text not null default 'off'
    check (mode in ('off', 'auto', 'stats', 'event', 'random', 'round_robin', 'hybrid')),
  interval_minutes integer not null default 50 check (interval_minutes >= 5),
  daily_limit integer not null default 12 check (daily_limit between 1 and 24),
  quiet_hours jsonb not null default
    '{"enabled":false,"start":"22:00","end":"06:00"}'::jsonb,
  templates jsonb not null default '{}'::jsonb,
  topics jsonb not null default '[]'::jsonb,
  random_pool jsonb not null default '[]'::jsonb,
  no_repeat_window integer not null default 10 check (no_repeat_window between 0 and 100),
  event_hooks jsonb not null default
    '{"new_listing":false,"released":false,"paid":false,"booking_confirmed":false}'::jsonb,
  require_approval boolean not null default true,
  last_event_at timestamptz,
  updated_by text,
  updated_at timestamptz not null default now()
);

insert into public.whatsapp_status_settings (id)
values (1)
on conflict (id) do nothing;

alter table public.whatsapp_status_settings enable row level security;

-- Everything the bot has posted as a status. Used for no-repeat, round-robin
-- ordering and the admin history view.
create table if not exists public.whatsapp_status_history (
  id bigint generated by default as identity primary key,
  mode text not null,
  topic text,
  body text not null,
  kind text not null default 'scheduled'
    check (kind in ('scheduled', 'event', 'manual')),
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists whatsapp_status_history_created_idx
  on public.whatsapp_status_history (created_at desc);

create index if not exists whatsapp_status_history_body_idx
  on public.whatsapp_status_history (body, created_at desc);

alter table public.whatsapp_status_history enable row level security;

comment on table public.whatsapp_bot_rules is 'Singleton JSON rule set for Ase replies (last-speaker guard, quiet hours, limits).';
comment on table public.whatsapp_status_settings is 'Singleton config for WhatsApp status modes: stats, event, random, round robin, hybrid.';
comment on table public.whatsapp_status_history is 'Status posts used for no-repeat and round-robin ordering.';
