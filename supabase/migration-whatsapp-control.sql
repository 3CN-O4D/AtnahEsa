-- WhatsApp bot control, transcripts, urgent alerts and marketing.
--
-- Service-role only: RLS is enabled with no policies. The Baileys worker and
-- the Next.js admin APIs use the service-role key; browsers never touch these
-- tables directly.

-- ------------------------------------------------------------------ control
-- One row. `mode` pauses every AI reply; the allow/block lists are digits-only
-- phone numbers. An empty allowlist means "AI may reply to anyone".
create table if not exists public.whatsapp_bot_control (
  id smallint primary key default 1 check (id = 1),
  mode text not null default 'active' check (mode in ('active', 'paused')),
  allowlist jsonb not null default '[]'::jsonb,
  blocklist jsonb not null default '[]'::jsonb,
  marketing_enabled boolean not null default false,
  require_approval boolean not null default true,
  status_interval_minutes integer not null default 180 check (status_interval_minutes >= 60),
  group_interval_minutes integer not null default 1440 check (group_interval_minutes >= 180),
  status_daily_limit integer not null default 8 check (status_daily_limit between 1 and 24),
  group_daily_limit integer not null default 3 check (group_daily_limit between 1 and 50),
  last_status_at timestamptz,
  last_group_at timestamptz,
  updated_by text,
  updated_at timestamptz not null default now()
);

insert into public.whatsapp_bot_control (id)
values (1)
on conflict (id) do nothing;

alter table public.whatsapp_bot_control enable row level security;

-- Per-chat AI switch + the one-time "a human will reply" marker.
alter table public.whatsapp_sessions
  add column if not exists ai_enabled boolean not null default true,
  add column if not exists handoff_at timestamptz;

-- ---------------------------------------------------------------- transcripts
-- Full conversation log for `.transcript` and the admin chat viewer. OTP rows
-- are stored with kind = 'otp' and hidden from exports.
create table if not exists public.whatsapp_messages (
  id bigint generated by default as identity primary key,
  wa_jid text not null,
  phone text,
  role text not null check (role in ('user', 'assistant', 'admin', 'system')),
  body text not null,
  message_id text,
  kind text,
  created_at timestamptz not null default now()
);

create index if not exists whatsapp_messages_jid_idx
  on public.whatsapp_messages (wa_jid, created_at desc);

create index if not exists whatsapp_messages_phone_idx
  on public.whatsapp_messages (phone, created_at desc);

alter table public.whatsapp_messages enable row level security;

-- ------------------------------------------------------------------ urgent
-- A feed the admin panel can acknowledge. The brain's `notify_admin` urgent
-- alerts and manual escalations land here.
create table if not exists public.whatsapp_urgent (
  id uuid primary key default gen_random_uuid(),
  phone text,
  name text,
  topic text,
  subject text,
  message text not null,
  priority text not null default 'urgent' check (priority in ('low', 'normal', 'high', 'urgent')),
  status text not null default 'open' check (status in ('open', 'acknowledged', 'resolved')),
  meta jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  acknowledged_by text,
  acknowledged_at timestamptz,
  resolved_at timestamptz
);

create index if not exists whatsapp_urgent_open_idx
  on public.whatsapp_urgent (status, created_at desc);

alter table public.whatsapp_urgent enable row level security;

-- ---------------------------------------------------------------- marketing
-- Draft → approved → sent. The worker only sends rows that are approved and
-- due, so nothing leaves the number without either an admin approval or the
-- explicit `require_approval = false` setting.
create table if not exists public.whatsapp_marketing (
  id uuid primary key default gen_random_uuid(),
  channel text not null check (channel in ('status', 'group')),
  target_jid text,
  body text not null,
  image_url text,
  listing_id uuid references public.listings(id) on delete set null,
  template text,
  status text not null default 'draft'
    check (status in ('draft', 'approved', 'scheduled', 'sending', 'sent', 'failed', 'skipped')),
  scheduled_for timestamptz not null default now(),
  sent_at timestamptz,
  error text,
  meta jsonb not null default '{}'::jsonb,
  created_by text,
  approved_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists whatsapp_marketing_due_idx
  on public.whatsapp_marketing (status, scheduled_for);

create index if not exists whatsapp_marketing_listing_idx
  on public.whatsapp_marketing (listing_id, created_at desc);

alter table public.whatsapp_marketing enable row level security;

-- Groups the number is in. The worker discovers them on connect and inserts
-- them disabled; an admin explicitly enables the ones that are fair game.
create table if not exists public.whatsapp_marketing_groups (
  jid text primary key,
  name text,
  enabled boolean not null default false,
  cadence_minutes integer not null default 1440 check (cadence_minutes >= 180),
  last_posted_at timestamptz,
  member_count integer,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.whatsapp_marketing_groups enable row level security;

-- ------------------------------------------------------------------- audit
create table if not exists public.whatsapp_control_audit (
  id bigint generated by default as identity primary key,
  actor text,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists whatsapp_control_audit_idx
  on public.whatsapp_control_audit (created_at desc);

alter table public.whatsapp_control_audit enable row level security;

-- Housekeeping for transcripts (keep 120 days).
create or replace function public.prune_whatsapp_messages()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.whatsapp_messages
  where created_at < now() - interval '120 days';
$$;

comment on table public.whatsapp_bot_control is 'Singleton WhatsApp bot control: pause, allow/block lists, marketing cadence.';
comment on table public.whatsapp_messages is 'Full WhatsApp conversation transcript used by the admin panel and .transcript.';
comment on table public.whatsapp_marketing is 'Approval queue for WhatsApp status and group marketing posts.';
